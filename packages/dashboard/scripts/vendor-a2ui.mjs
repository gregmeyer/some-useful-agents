#!/usr/bin/env node
/**
 * Rebuild sua's vendored A2UI (protocol v1.0, ADR-0084) from the A2UI repo at
 * a pinned commit: the 1.0 renderer is on its main branch but not yet on npm
 * (@a2ui/web_core and @a2ui/lit 0.16). Two files, both checked in:
 *
 *   packages/dashboard/src/assets/vendor/a2ui-v1_0.js  the browser renderer, ONE
 *     ES module, so the dashboard loads it with <script type="module"> under its
 *     CSP (no CDN scripts).
 *   packages/core/vendor/a2ui-web-core-v1.mjs  the same web_core for Node, so the
 *     server validates views with the very code the browser draws them with.
 *
 *   node packages/dashboard/scripts/vendor-a2ui.mjs
 *
 * Bump A2UI_COMMIT (and the version) to update; when 0.16 is on npm, this can
 * install it from there instead. Needs git, corepack (yarn 4) and network.
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, rmSync, statSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const A2UI_COMMIT = '496df0e76e2ad9aba4cc2a12abe066f43d4f171d';
export const A2UI_VERSION = '0.16.0';
const ESBUILD = '0.25.12';
const here = dirname(fileURLToPath(import.meta.url));
const browserOut = resolve(here, '..', 'src', 'assets', 'vendor', 'a2ui-v1_0.js');
const serverOut = resolve(here, '..', '..', 'core', 'vendor', 'a2ui-web-core-v1.mjs');
const dir = mkdtempSync(join(tmpdir(), 'sua-a2ui-vendor-'));
const run = (cmd, args, cwd, env = {}) => execFileSync(cmd, args, { cwd, stdio: 'inherit', env: { ...process.env, ...env } });
try {
  const repo = join(dir, 'a2ui');
  run('git', ['init', '-q', repo], dir);
  run('git', ['fetch', '-q', '--depth', '1', 'https://github.com/a2ui-project/a2ui.git', A2UI_COMMIT], repo);
  run('git', ['checkout', '-q', 'FETCH_HEAD'], repo);
  run('corepack', ['yarn', 'workspaces', 'focus', '@a2ui/lit', '@a2ui/web_core'], repo, { YARN_ENABLE_SCRIPTS: '0' });
  run('corepack', ['yarn', 'run', 'build'], join(repo, 'typescript', 'renderers', 'lit'));
  const tools = join(dir, 'tools');
  mkdirSync(tools);
  writeFileSync(join(tools, 'package.json'), JSON.stringify({ name: 'a2ui-vendor-tools', private: true }));
  run('npm', ['install', '--silent', '--no-audit', '--no-fund', `esbuild@${ESBUILD}`], tools);
  const esbuild = join(tools, 'node_modules', '.bin', 'esbuild');
  const wc = join(repo, 'typescript', 'core', 'web_core', 'dist', 'src');
  const lit = join(repo, 'typescript', 'renderers', 'lit', 'dist', 'src');
  const head = `// sua's vendored A2UI (protocol v1.0), web_core and lit ${A2UI_VERSION} at a2ui-project/a2ui@${A2UI_COMMIT.slice(0, 12)}. Generated by packages/dashboard/scripts/vendor-a2ui.mjs; do not edit.`;
  writeFileSync(join(repo, 'entry-browser.js'), [head,
    `export { MessageProcessor, Catalog } from '${wc}/index.js';`,
    `export { CommonSchemas } from '${wc}/v1_0/index.js';`,
    `export { A2uiLitElement } from '${wc}/universal/index.js';`,
    `export { basicCatalog, setMarkdownRenderer } from '${wc}/catalogs/basic/v1/index.js';`,
    `export { A2uiSurface } from '${lit}/index.js';`,
    "export { html, css, nothing } from 'lit';",
    "export { z } from 'zod';",
    `export const A2UI_VENDORED = ${JSON.stringify({ version: A2UI_VERSION, commit: A2UI_COMMIT })};`, ''].join('\n'));
  writeFileSync(join(repo, 'entry-server.js'), [head,
    `export { MessageProcessor, Catalog, STRICT_VALIDATION } from '${wc}/index.js';`,
    `export { CommonSchemas } from '${wc}/v1_0/index.js';`,
    `export { basicCatalog, BASIC_FUNCTIONS } from '${wc}/catalogs/basic/v1/index.js';`,
    "export { z } from 'zod';",
    `export const A2UI_VENDORED = ${JSON.stringify({ version: A2UI_VERSION, commit: A2UI_COMMIT })};`, ''].join('\n'));
  const nodePaths = join(repo, 'node_modules');
  run(esbuild, ['entry-browser.js', '--bundle', '--format=esm', '--minify', '--target=es2022', '--legal-comments=eof', `--banner:js=${head}`, `--outfile=${browserOut}`], repo, { NODE_PATH: nodePaths });
  mkdirSync(dirname(serverOut), { recursive: true });
  run(esbuild, ['entry-server.js', '--bundle', '--format=esm', '--platform=node', '--target=node20', '--legal-comments=eof', `--banner:js=${head}`, `--outfile=${serverOut}`], repo, { NODE_PATH: nodePaths });
  console.log(`wrote ${browserOut} (${Math.round(statSync(browserOut).size / 1024)} KB)`);
  console.log(`wrote ${serverOut} (${Math.round(statSync(serverOut).size / 1024)} KB)`);
} finally {
  rmSync(dir, { recursive: true, force: true });
}
