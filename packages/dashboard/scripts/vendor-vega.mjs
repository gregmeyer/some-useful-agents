#!/usr/bin/env node
/**
 * Rebuild src/assets/vendor/a2ui-vega.js: Vega and Vega-Lite as ONE ES
 * module, loaded only by a page that draws a VegaChart (ADR-0089). It draws
 * safely under the dashboard's CSP: expressions run through vega-interpreter
 * (no eval), and a loader that refuses every request, so a chart shows only
 * the data its spec carries (no outside data, images or links). Run it when
 * bumping the pinned versions; the output is checked in.
 *
 *   node packages/dashboard/scripts/vendor-vega.mjs
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, rmSync, statSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const VEGA_VERSIONS = { vega: '6.4.0', 'vega-lite': '6.5.0', 'vega-embed': '7.3.0', 'vega-interpreter': '2.3.2', esbuild: '0.25.12' };
const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '..', 'src', 'assets', 'vendor', 'a2ui-vega.js');
const dir = mkdtempSync(join(tmpdir(), 'sua-vega-vendor-'));
try {
  writeFileSync(join(dir, 'package.json'), JSON.stringify({ name: 'vega-vendor', private: true, type: 'module' }));
  execFileSync('npm', ['install', '--silent', '--no-audit', '--no-fund', ...Object.entries(VEGA_VERSIONS).map(([k, v]) => `${k}@${v}`)], { cwd: dir, stdio: 'inherit' });
  const head = `// sua's vendored Vega (vega ${VEGA_VERSIONS.vega}, vega-lite ${VEGA_VERSIONS['vega-lite']}, vega-embed ${VEGA_VERSIONS['vega-embed']}, vega-interpreter ${VEGA_VERSIONS['vega-interpreter']}). Generated by packages/dashboard/scripts/vendor-vega.mjs; do not edit.`;
  writeFileSync(join(dir, 'entry.js'), [
    head,
    "import embed from 'vega-embed';",
    "import { loader } from 'vega';",
    "import { expressionInterpreter } from 'vega-interpreter';",
    '',
    '/** A loader that fetches nothing: no outside data, images or links in a chart. */',
    'function refusing() {',
    '  const l = loader();',
    "  const no = (what) => () => Promise.reject(new Error(`A chart can't load ${what}; give it its data in the spec.`));",
    "  l.load = no('data'); l.sanitize = no('links or images'); l.http = no('data'); l.file = no('files');",
    '  return l;',
    '}',
    '',
    '/** Draw a Vega or Vega-Lite spec into `el`, CSP-safe (no eval), with nothing fetched. */',
    'export function drawVega(el, spec, options = {}) {',
    "  return embed(el, spec, { actions: false, renderer: 'svg', ast: true, expr: expressionInterpreter, loader: refusing(), ...options });",
    '}',
    '',
  ].join('\n'));
  execFileSync(join(dir, 'node_modules', '.bin', 'esbuild'), [
    'entry.js', '--bundle', '--format=esm', '--minify', '--target=es2022', '--legal-comments=eof', `--banner:js=${head}`, `--outfile=${out}`,
  ], { cwd: dir, stdio: 'inherit' });
  console.log(`wrote ${out} (${Math.round(statSync(out).size / 1024)} KB)`);
} finally {
  rmSync(dir, { recursive: true, force: true });
}
